#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════
// The Buy Abyss — seed generator: the 2026 sheet and the WBBM rate
// history into real rows, as SQL you can run anywhere.
// ═══════════════════════════════════════════════════════════════════
//   node scripts/buy-abyss-seed.js            → writes supabase/buy_abyss_seed.sql
//   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f supabase/buy_abyss_seed.sql
//   (or paste it into the Supabase SQL editor after buy_abyss.sql)
//
// What it writes, idempotently:
//   • ba_import_batch  one for data/buy-abyss/lr2026.json (purpose history_2026,
//                      raw preserved, reconciliation report attached) and one
//                      for data/buy-abyss/wbbm-2026-orders.json (rate_history)
//   • ba_history_2026  one row per station × section × month from the sheet
//   • ba_station       every line stationsFrom() derives per market — the
//                      prototype's station record, 2026 booked/actual attached
//   • ba_rate_history  one row per WBBM 2026 order line
//
// Reconciliation: lr2026.json is the sheet already normalized by the
// prototype's build step; it carries no totals of its own, so every
// footing dimension is reported as unverifiable and the batch is stored
// with reconciled = false. Footing against the OTM workbook itself is
// the outstanding Phase 1 acceptance step (see scripts/buy-abyss-import.js).
// ═══════════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const core = require('../buy-abyss-core.js');
const { reconcile } = require('./buy-abyss-import.js');

const LR26 = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/buy-abyss/lr2026.json'), 'utf8'));
const WBBM = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/buy-abyss/wbbm-2026-orders.json'), 'utf8'));
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');
const uuidFrom = (s) => { const h = crypto.createHash('md5').update(s).digest('hex'); return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`; };
const lit = (v) => v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : typeof v === 'boolean' ? (v ? 'true' : 'false') : "'" + String(v).replace(/'/g, "''") + "'";
const jlit = (v) => '$j$' + JSON.stringify(v) + '$j$::jsonb';
const arr = (a) => a ? 'array[' + a.map(Number).join(',') + ']::numeric[]' : 'null';

const out = [];
out.push('-- Generated by scripts/buy-abyss-seed.js — do not edit by hand. Re-run the script instead.');
out.push('-- Run after supabase/buy_abyss.sql. Safe to re-run.');
out.push('begin;');

// ── 1. the 2026 sheet ─────────────────────────────────────────────
const lrRaw = JSON.stringify(LR26);
const lrBatch = uuidFrom('lr2026:' + sha(lrRaw));
const rows = [];
Object.entries(LR26).forEach(([market, rs]) => rs.forEach((r, i) => { for (let m = 1; m <= 12; m++) rows.push({ market, section: r.section, media: core.mediumOf(r.station, (r.section || '').toLowerCase()), station: r.station.trim(), year: 2026, month: m, booked: r.booked[m - 1], actual: r.actual[m - 1], source_ref: `${market}!row${i + 1}`, raw: r }); }));
const report = reconcile(rows.map(r => ({ ...r, media: r.media || 'TV' })), {});   // no totals in the JSON → unverifiable, honestly
out.push(`insert into ba_import_batch (id, purpose, source_agency, source_workbook, source_file, source_sha256, imported_by, raw, row_count, reconciliation, reconciled, note)
values (${lit(lrBatch)}, 'history_2026', 'OTM', 'L&R 2026 media sheet', 'data/buy-abyss/lr2026.json', ${lit(sha(lrRaw))}, 'scripts/buy-abyss-seed.js', ${jlit(LR26)}, ${rows.length}, ${jlit(report)}, false,
        'lr2026.json is the sheet as the prototype normalized it; it carries no source totals, so nothing could be footed. Foot against the OTM workbook with scripts/buy-abyss-import.js before these figures are trusted beyond reference.')
on conflict (id) do update set raw = excluded.raw, row_count = excluded.row_count, reconciliation = excluded.reconciliation, note = excluded.note;`);
out.push(`delete from ba_history_2026 where import_batch_id = ${lit(lrBatch)};`);
const chunk = 400;
for (let i = 0; i < rows.length; i += chunk) {
  out.push('insert into ba_history_2026 (import_batch_id, market, section, media, station, year, month, booked, actual, source_ref, raw) values\n' +
    rows.slice(i, i + chunk).map(r => `(${lit(lrBatch)}, ${lit(r.market)}, ${lit(r.section)}, ${lit(r.media)}, ${lit(r.station)}, 2026, ${r.month}, ${lit(r.booked)}, ${lit(r.actual)}, ${lit(r.source_ref)}, ${jlit(r.raw)})`).join(',\n') + ';');
}

// ── 2. stations per market, exactly as stationsFrom() derives them ──
const MARKETS = core.buildMarkets(LR26);
MARKETS.forEach(b => {
  Object.entries(b.stations).forEach(([key, s]) => {
    out.push(`insert into ba_station (market_year_id, call_sign, media, aff, owner, owner_source, pkg, vendor, cable, booked26, actual26, added, on_buy, added_from)
select id, ${lit(key)}, ${lit(s.medium)}, ${lit(s.aff)}, ${lit(s.own || '')}, ${s.own ? (s.medium === 'Radio' && core.OWN_RADIO[core.callOf(key)] ? "'OWN_RADIO'" : core.OWN[core.callOf(key)] ? "'OWN'" : "'manual'") : 'null'}, ${lit(!!s.pkg)}, ${lit(!!s.vendor)}, ${lit(!!s.cable)}, ${arr(s.booked26)}, ${arr(s.actual26)}, false, true, 'history'
from ba_market_year where market = ${lit(b.market)} and year = 2027
on conflict (market_year_id, call_sign) do update set media = excluded.media, aff = excluded.aff, pkg = excluded.pkg, vendor = excluded.vendor, cable = excluded.cable, booked26 = excluded.booked26, actual26 = excluded.actual26,
  owner = case when ba_station.owner_source in ('web','manual') and coalesce(ba_station.owner,'') <> '' then ba_station.owner else excluded.owner end,
  owner_source = case when ba_station.owner_source in ('web','manual') and coalesce(ba_station.owner,'') <> '' then ba_station.owner_source else excluded.owner_source end;`);
  });
});

// ── 3. WBBM 2026 orders: the rate history for Chicago ────────────
const wbRaw = JSON.stringify({ market: 'Chicago', label: 'Atticor 2026 rate history (Postman Law annual)', weeks: WBBM.weeks, stations: WBBM.stations, orders: WBBM.orders });
const wbBatch = uuidFrom('wbbm2026:' + sha(wbRaw));
out.push(`insert into ba_import_batch (id, purpose, source_agency, source_workbook, source_file, source_sha256, imported_by, raw, row_count, reconciled, note)
values (${lit(wbBatch)}, 'rate_history', 'Atticor', 'WBBM Postman Law Chicago 2026 contracts (4 WideOrbit orders)', 'data/buy-abyss/wbbm-2026-orders.json', ${lit(sha(wbRaw))}, 'scripts/buy-abyss-seed.js', $j$${wbRaw}$j$::jsonb, ${WBBM.orders.reduce((a, o) => a + o.lines.length, 0)}, true,
        'Every line foots to its printed amount and each order to printed gross/net (read_lines.py, reproduced by api/buy-abyss.js footOrder).')
on conflict (id) do update set raw = excluded.raw, row_count = excluded.row_count, note = excluded.note;`);
out.push(`delete from ba_rate_history where import_batch_id = ${lit(wbBatch)};`);
const rh = [];
WBBM.orders.forEach(o => { const [ps, pe] = String(o.flight || '').split(' - ').map(s => { const [m, d, y] = s.trim().split('/'); return y && m && d ? `20${y}-${m.padStart(2, '0')}-${d.padStart(2, '0')}` : null; });
  o.lines.forEach(l => rh.push(`(${lit(wbBatch)}, 'Lerner & Rowe', 'Chicago', 'WBBM', 'TV', 2026, ${lit(l.daypart)}, ${lit(core.lenOf(l))}, ${lit(l.program)}, ${lit(l.rate)}, ${lit(l.spots)}, ${lit(l.gross)}, ${lit(l.net)}, ${lit(ps)}, ${lit(pe)}, ${lit('WideOrbit order ' + o.order + ' · ' + o.desc + ' · ' + o.file)})`)); });
out.push('insert into ba_rate_history (import_batch_id, brand, market, station, media, year, daypart, spot_len, program, rate, spots, gross, net, period_start, period_end, source) values\n' + rh.join(',\n') + ';');
out.push('commit;');

const dest = path.join(__dirname, '../supabase/buy_abyss_seed.sql');
fs.writeFileSync(dest, out.join('\n\n') + '\n');
console.log(`wrote ${dest}: ${rows.length} history rows (${Object.keys(LR26).length} markets), ${MARKETS.reduce((a, b) => a + Object.keys(b.stations).length, 0)} stations in ${MARKETS.length} markets, ${rh.length} rate-history lines`);
console.log('reconciliation: ' + report.summary.join(' | '));
